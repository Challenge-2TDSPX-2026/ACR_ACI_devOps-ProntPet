CREATE TABLE TB_OWNER (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(255),
    CPF VARCHAR2(255),
    EMAIL VARCHAR2(255),
    PHONE VARCHAR2(255),

    CONSTRAINT PK_TB_OWNER PRIMARY KEY (ID)
);

CREATE TABLE TB_CLINIC (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(255),
    CNPJ VARCHAR2(255),
    ADDRESS VARCHAR2(255),
    PHONE VARCHAR2(255),
    OPENING_HOURS TIMESTAMP,
    CLOSING_HOURS TIMESTAMP,

    CONSTRAINT PK_TB_CLINIC PRIMARY KEY (ID)
);

CREATE TABLE TB_ACCOUNT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EMAIL VARCHAR2(255) NOT NULL,
    PASSWORD VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(50) NOT NULL,

    OWNER_ID NUMBER,
    CLINIC_ID NUMBER,

    CONSTRAINT PK_TB_ACCOUNT PRIMARY KEY (ID),

    CONSTRAINT FK_ACCOUNT_OWNER
        FOREIGN KEY (OWNER_ID)
        REFERENCES TB_OWNER(ID),

    CONSTRAINT FK_ACCOUNT_CLINIC
        FOREIGN KEY (CLINIC_ID)
        REFERENCES TB_CLINIC(ID),

    CONSTRAINT UK_ACCOUNT_OWNER
        UNIQUE (OWNER_ID)
);

CREATE TABLE TB_PET (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(255),
    SPECIES VARCHAR2(255),
    BREED VARCHAR2(255),
    BIRTH_DATE DATE,
    WEIGHT NUMBER(10,2),
    SEX VARCHAR2(50),
    OWNER_ID NUMBER,

    CONSTRAINT PK_TB_PET PRIMARY KEY (ID),

    CONSTRAINT FK_PET_OWNER
        FOREIGN KEY (OWNER_ID)
        REFERENCES TB_OWNER(ID)
);

CREATE TABLE TB_APPOINTMENT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SPECIALITY VARCHAR2(255),
    SYMPTOMS VARCHAR2(255),
    DIGNOSIS VARCHAR2(255),
    OBSERVATIONS VARCHAR2(255),
    APPOINTMENT_DATE TIMESTAMP,
    UPDATED_WEIGHT NUMBER(10,2),

    CLINIC_ID NUMBER,
    PET_ID NUMBER,

    CONSTRAINT PK_TB_APPOINTMENT PRIMARY KEY (ID),

    CONSTRAINT FK_APPOINTMENT_CLINIC
        FOREIGN KEY (CLINIC_ID)
        REFERENCES TB_CLINIC(ID),

    CONSTRAINT FK_APPOINTMENT_PET
        FOREIGN KEY (PET_ID)
        REFERENCES TB_PET(ID)
);